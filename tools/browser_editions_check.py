"""Edition integration checks, called by browser_catalog_check.py --editions."""
import json
from browser_check import CDP


def run(args):
    cdp=CDP(args.port)
    checks=[]
    def language(code):
        cdp.evaluate("(() => {const e=document.querySelector('.compact-language select');e.value="+json.dumps(code)+";e.dispatchEvent(new Event('change',{bubbles:true}));})()")
        cdp.wait("document.documentElement.lang==="+json.dumps(code))
    def close():
        cdp.evaluate("[...document.querySelectorAll('dialog[open] .modal-head .icon-button')].at(-1).click()")
    def overflow(): return cdp.evaluate("document.documentElement.scrollWidth>innerWidth || [...document.querySelectorAll('dialog[open]')].some(d=>d.scrollWidth>d.clientWidth+1)")
    def assert_text(selector, text):
        cdp.wait("document.querySelector("+json.dumps(selector)+")?.textContent.includes("+json.dumps(text)+")")

    cdp.call('Page.navigate',{'url':args.url})
    cdp.wait("document.querySelectorAll('.game-card').length>0")
    boot=cdp.evaluate("fetch('/api/bootstrap').then(r=>r.json())")
    pinyon=next(s for s in boot['sources'] if s['id']=='pinyon')
    assert pinyon['name']=='Pinyon Shift' and pinyon.get('edition')!='recopile'
    assert boot['app_notice']['privacy'].startswith('# RE:COPILE privacy notice')
    if cdp.evaluate("Boolean(document.querySelector('.app-attribution'))"):
        assert_text('.app-attribution','GNU GPLv3')
        assert not cdp.evaluate("document.querySelector('.app-attribution').textContent.includes('komercja wymaga')")
        cdp.evaluate("[...document.querySelectorAll('dialog .tabs button')][1].click()")
        assert_text('dialog .document-text','GNU GENERAL PUBLIC LICENSE')
        cdp.capture(args.output/'gplv3-notice.png')
        cdp.evaluate("document.querySelector('dialog input[type=checkbox]')?.click()")
        cdp.evaluate("document.querySelector('dialog .modal-actions button.primary').click()")
        cdp.wait("!document.querySelector('dialog[open]')")
        checks.append('GPLv3 notice shows the full license and retains author attribution')
    cdp.evaluate("window.dispatchEvent(new Event('recopile:license'))")
    cdp.wait("document.querySelector('.app-attribution')")
    cdp.evaluate("[...document.querySelectorAll('dialog .tabs button')][2].click()")
    assert_text('dialog .document-text','# RE:COPILE privacy notice')
    cdp.capture(args.output/'privacy-en.png')
    cdp.evaluate("document.querySelector('dialog .modal-actions button.primary').click()")
    cdp.wait("!document.querySelector('dialog[open]')")
    checks.append('Privacy notice is English and Pinyon Shift retains its original project name')
    language('pl')
    cdp.click('Jak grać')
    cdp.wait("document.querySelectorAll('.how-to-play .play-steps li').length===7")
    assert_text('.how-to-play','Xbox 360 i PlayStation 2')
    assert_text('.how-to-play','Xbox One')
    assert_text('.xbox-copy-guide','GOD2ISO')
    assert_text('.ps2-disc-reader','PlayStation 2')
    assert not cdp.evaluate("/Pinyon|Forza Horizon/.test(document.querySelector('.tools-page').textContent)")
    links=cdp.evaluate("[...document.querySelectorAll('.disc-tools .guide-row')].map(a=>a.href)")
    assert 'https://github.com/arcanite24/shiftglue-sdk' in links
    assert 'https://github.com/xenia-project/xenia/wiki/Quickstart' in links
    assert 'https://github.com/ran-j/PS2Recomp' in links
    checks.append('Shared Xbox 360/PS2 app guide; ShiftGlue, Xenia and PS2Recomp links; separate USB and DVD preparation')
    for code, first, label in [('en','Find a game and choose how to run it','Open library'),('hu','Keresd meg a játékot','Könyvtár megnyitása'),('pl','Znajdź grę','Otwórz bibliotekę')]:
        language(code)
        assert_text('.how-to-play .play-steps li:first-child strong',first)
        assert_text('.how-to-play button',label)
        cdp.capture(args.output/('how-to-play-'+code+'.png'))
        assert not overflow()
    cdp.capture(args.output/'how-to-play-compact.png',447,800)
    assert not overflow()
    cdp.capture(args.output/'how-to-play-desktop.png')
    checks.append('Guide translated in EN/PL/HU and fits desktop/447px widths')

    cdp.click('Kolekcje')
    cdp.wait("document.querySelectorAll('.collection-tile').length===2")
    cdp.wait("[...document.querySelectorAll('.collection-tile img')].filter(i=>i.naturalWidth>0).length===2",timeout=45)
    cdp.capture(args.output/'collection-tiles.png')
    for collection,title in [('forza-horizon','Forza Collection'),('ratchet-and-clank','Ratchet & Clank Collection')]:
        cdp.evaluate("[...document.querySelectorAll('.collection-tile')].find(b=>b.querySelector('h2').textContent==="+json.dumps(title)+").click()")
        cdp.wait("document.querySelector('.collection-detail')?.dataset.collection==="+json.dumps(collection))
        if collection=='forza-horizon':
            assert cdp.evaluate('''document.querySelector('[data-title="Forza Horizon 5"] a[href]')?.href==='https://store.steampowered.com/app/1551360/' ''')
            for game in ['Forza Horizon 3','Forza Horizon 4']:
                assert_text('[data-title="'+game+'"]','Wycofana ze sprzedaży')
                assert not cdp.evaluate("document.querySelector("+json.dumps('[data-title="'+game+'"]')+").textContent.includes('Kup na Steam')")
            assert not cdp.evaluate("document.querySelector('.collection-detail').textContent.includes('Ratchet 3')")
        else:
            assert cdp.evaluate('''document.querySelector('[data-title="Ratchet & Clank: Rift Apart"] a[href]')?.href==='https://store.steampowered.com/app/1895880/' ''')
            cdp.evaluate('''document.querySelector('[data-title="Ratchet & Clank: Rift Apart"] .collection-pc-actions button').click()''')
            cdp.wait("document.querySelector('dialog .add-form input')?.value==='Ratchet & Clank: Rift Apart'")
            assert_text('dialog .tabs .active','Gra spoza launchera')
            close()
        cdp.capture(args.output/(collection+'-collection.png'))
        cdp.capture(args.output/(collection+'-collection-compact.png'),447,800)
        assert not overflow()
        cdp.click('Wszystkie kolekcje')
        cdp.wait("document.querySelector('.collection-tile')")
    for code,label in [('en','Open collection'),('hu','Gyűjtemény megnyitása'),('pl','Otwórz kolekcję')]:
        language(code)
        assert_text('.collection-tile',label)
    checks.append('First-game cover tiles open dedicated series views; Steam purchase links, delisted FH3/FH4, prefilled PC import and compact layout')
    cdp.click('Jak grać')
    cdp.click('Otwórz bibliotekę')
    cdp.wait("document.querySelector('.game-title')")
    cdp.click('Forza Horizon')
    cdp.wait("document.querySelector('dialog .detail-body')")
    assert_text('dialog .detail-body','Pinyon Shift')
    assert not cdp.evaluate("document.querySelector('dialog .detail-body').textContent.includes('RE:COPILE Edition')")
    cdp.click('Przygotuj w RE:COPILE')
    cdp.wait("document.querySelector('.port-setup-panel')")
    assert cdp.evaluate("[...document.querySelectorAll('.port-setup-actions button')].every(b=>b.disabled)")
    cdp.input('#port-input','/path/to/your-own.iso')
    assert cdp.evaluate("[...document.querySelectorAll('.port-setup-actions button')].every(b=>b.disabled)")
    cdp.evaluate("document.querySelector('.port-setup-panel input[type=checkbox]').click()")
    cdp.wait("[...document.querySelectorAll('.port-setup-actions button')].every(b=>!b.disabled)")
    # No preparation starts: this validates form gating without actual game input.
    assert not cdp.evaluate("[...document.querySelectorAll('dialog .detail-actions button')].some(b=>b.textContent.trim()==='Graj')")
    for code,label in [('en','Check and build'),('hu','Ellenőrzés és fordítás'),('pl','Sprawdź i zbuduj')]:
        language(code)
        assert_text('.port-setup-actions',label)
        cdp.capture(args.output/('forza-setup-'+code+'.png'))
    cdp.capture(args.output/'forza-setup-compact.png',447,800)
    assert not overflow()
    cdp.capture(args.output/'forza-setup-desktop.png')
    checks.append('Forza has one setup panel in EN/PL/HU, gated by path and ownership; downloaded tools do not enable Play')
    close()

    cdp.click('Źródła')
    cdp.wait("document.querySelectorAll('.source-card').length===13")
    cards=cdp.evaluate("[...document.querySelectorAll('.source-card')].filter(c=>c.querySelector('h3').textContent.includes('Forza Horizon 2')).map(c=>({text:c.textContent,repo:c.querySelector('.source-card-head a')?.getAttribute('href')}))")
    assert len(cards)==3,cards
    assert all('Projekt eksperymentalny' in c['text'] and 'Windows' in c['text'] for c in cards),cards
    assert any('/MASELKO-95/Forza-Horizon-2-Recomp' in c['repo'] for c in cards)
    cdp.capture(args.output/'sources-with-experimental-fh2.png')
    checks.append('FH2 original/community/research forks retain development status and have no installable package')

    cdp.evaluate("[...document.querySelectorAll('.main-nav button')].find(b=>b.textContent.includes('Rekompilacje')).click()")
    cdp.wait("[...document.querySelectorAll('.game-title')].some(b=>b.textContent.includes('Up Your Arsenal'))")
    cdp.evaluate("[...document.querySelectorAll('.game-title')].find(b=>b.textContent.includes('Up Your Arsenal')).click()")
    cdp.wait("document.querySelector('dialog .detail-body')")
    assert_text('dialog .modal-head','Ratchet & Clank: Up Your Arsenal (Ratchet & Clank 3)')
    assert cdp.evaluate("[...document.querySelectorAll('dialog a')].some(a=>a.href==='https://github.com/MASELKO-95/ratchet-3-recopile-edition')")
    cdp.click('Zmień lokalny projekt')
    cdp.wait("document.querySelector('#ratchet-project-root')")
    assert cdp.evaluate("document.querySelector('#ratchet-project-root').value.endsWith('/Downloads/Ratchet')")
    assert_text('dialog .import-form','Pełna rozgrywka')
    assert cdp.evaluate("document.querySelector('dialog .import-form button.primary').disabled")
    cdp.capture(args.output/'up-your-arsenal-local-project.png')
    checks.append('Specific Up Your Arsenal / Ratchet 3 title, RE:COPILE Edition source, retained local project and unverified gameplay status')
    cdp.evaluate("document.querySelector('dialog .import-form .icon-button').click()")
    cdp.evaluate("[...document.querySelectorAll('dialog .document-source')].find(b=>b.tagName==='BUTTON').click()")
    cdp.wait("document.querySelector('.project-review-summary')",timeout=60)
    assert_text('dialog:last-of-type .document-text','Up Your Arsenal')
    cdp.evaluate("[...document.querySelectorAll('dialog[open]')].at(-1).querySelectorAll('.tabs button')[1].click()")
    assert_text('dialog:last-of-type .document-text','GNU GENERAL PUBLIC LICENSE')
    cdp.capture(args.output/'ratchet-upstream-gplv3.png')
    checks.append('Published Ratchet source supplies its actual README and GPLv3 document inside the hub')
    close();close()
    cdp.click('Emulatory')
    cdp.wait("document.querySelector('.engine-card')")
    cdp.evaluate("[...document.querySelectorAll('.engine-card button')].find(b=>b.textContent.includes('Zainstaluj silnik')).click()")
    cdp.wait("document.querySelector('.project-review-summary')",timeout=45)
    assert cdp.evaluate("document.querySelector('.project-license-consent input').disabled")
    cdp.evaluate("[...document.querySelectorAll('dialog input[type=checkbox]')][0].click()")
    assert cdp.evaluate("document.querySelector('dialog .modal-actions button.primary').disabled")
    cdp.evaluate("[...document.querySelectorAll('dialog .tabs button')].find(b=>b.textContent==='Licencja').click()")
    cdp.wait("!document.querySelector('.project-license-consent input').disabled")
    assert cdp.evaluate("document.querySelector('dialog .modal-actions button.primary').disabled")
    cdp.evaluate("document.querySelector('.project-license-consent input').click()")
    assert not cdp.evaluate("document.querySelector('dialog .modal-actions button.primary').disabled")
    for code,label in [('en',"I accept this project's license terms."),('hu','Elfogadom a projekt licencfeltételeit.'),('pl','Akceptuję warunki licencji tego projektu.')]:
        language(code)
        assert_text('.project-license-consent',label)
    cdp.capture(args.output/'separate-license-consent.png')
    # Do not download an emulator; the backend tests cover the authorized path.
    close()
    checks.append('Reading README alone cannot enable install; license must be opened and separately accepted in EN/PL/HU')
    assert not cdp.errors,cdp.errors
    report={'checks':checks,'console_errors':cdp.errors,'gameplay_validated':False}
    args.output.mkdir(parents=True,exist_ok=True)
    (args.output/'editions-browser-check.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps(report,ensure_ascii=False,indent=2))
